  const HTML_LANG = {"en": "en", "ru": "ru", "es": "es"};
  const OG_LOCALE = {"en": "en_ZA", "ru": "ru_RU", "es": "es_ES"};
  const UI_LOCALE = {"en": "en-ZA", "ru": "ru-RU", "es": "es-ES"};

  let current = "en";

  function t(key, vars) {
    const table = DICT[current] || DICT.en;
    let str = table[key] ?? DICT.en[key] ?? key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        str = str.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return str;
  }

  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && DICT[saved]) return saved;
    } catch (_) {}
    const params = new URLSearchParams(location.search);
    const q = (params.get("lang") || "").toLowerCase();
    if (DICT[q]) return q;
    const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    if (nav.startsWith("ru")) return "ru";
    if (nav.startsWith("es")) return "es";
    return "en";
  }

  function apply(lang, { persist } = { persist: true }) {
    if (!DICT[lang]) lang = "en";
    current = lang;
    if (persist) {
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    }
    document.documentElement.lang = HTML_LANG[lang] || lang;

    const title = t("meta.title");
    document.title = title;
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute("content", t("meta.description"));
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", title);
    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute("content", t("meta.description"));
    const ogLoc = document.querySelector('meta[property="og:locale"]');
    if (ogLoc) ogLoc.setAttribute("content", OG_LOCALE[lang] || "en_ZA");
    const twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute("content", title);
    const twDesc = document.querySelector('meta[name="twitter:description"]');
    if (twDesc) twDesc.setAttribute("content", t("meta.description"));

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "TITLE") el.textContent = val;
      else el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (!key) return;
      el.innerHTML = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    document.querySelectorAll("[data-i18n-value]").forEach((el) => {
      const key = el.getAttribute("data-i18n-value");
      if (key) el.value = t(key);
    });

    // subject hidden field
    const subject = document.querySelector('#contact-form input[name="subject"]');
    if (subject) subject.value = t("contact.subject");

    document.querySelectorAll("[data-lang]").forEach((btn) => {
      const active = btn.getAttribute("data-lang") === lang;
      btn.classList.toggle("is-active", active);
      btn.setAttribute("aria-pressed", active ? "true" : "false");
    });

    // Update URL ?lang= without reload (SEO-friendly shareable)
    try {
      const url = new URL(location.href);
      url.searchParams.set("lang", lang);
      history.replaceState(null, "", url);
    } catch (_) {}

    document.dispatchEvent(new CustomEvent("allsorted:lang", { detail: { lang } }));
  }

  function wire() {
    document.querySelectorAll("[data-lang]").forEach((btn) => {
      btn.addEventListener("click", () => apply(btn.getAttribute("data-lang"), { persist: true }));
    });
  }

  function init() {
    wire();
    apply(detect(), { persist: false });
    // Persist detected choice so next visit is stable (only if nothing stored)
    try {
      if (!localStorage.getItem(STORAGE_KEY)) localStorage.setItem(STORAGE_KEY, current);
    } catch (_) {}
  }

  return {
    t,
    apply,
    init,
    get lang() { return current; },
    get uiLocale() { return UI_LOCALE[current] || "en-ZA"; },
    DICT,
  };
